#!/usr/bin/env python3
"""Copy the four USB descriptors verbatim from PicoSwitch (MIT licensed)."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
source = (ROOT / 'PicoSwitch/include/SwitchConsts.h').read_text(encoding='utf-8')
out = ['// Generated by tools/sync_descriptors.py from PicoSwitch/include/SwitchConsts.h.',
       '// Copyright (c) 2026 Gezine. MIT; see ../LICENSE. See README for upstream credits.',
       '#pragma once', '#include <stdint.h>', '// clang-format off', '']
for name in ['switch_usb_device_descriptor', 'switch_usb_configuration_descriptor',
             'switch_usb_report_descriptor', 'keyboard_usb_report_descriptor']:
    body = re.search(r'static const uint8_t ' + name + r'\[\] = \{(.*?)\};', source, re.S).group(1)
    body = re.sub(r'//[^\n]*', '', body)
    values = [int(v.strip(), 0) for v in body.split(',') if v.strip()]
    out.append(f'static uint8_t {name}[] = {{')
    for i in range(0, len(values), 12):
        out.append('    ' + ', '.join(f'0x{v:02x}' for v in values[i:i+12]) + ',')
    out.append('};\n')
out.append('// clang-format on\n')
(ROOT / 'FlipperSwitch/civ_descriptors.h').write_text('\n'.join(out), encoding='utf-8')
